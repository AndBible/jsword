#!/usr/bin/env python3
"""Embed exact frozen oracle fields; never run the implementation to obtain expectations."""
import argparse
import hashlib
import json
import re
from pathlib import Path


def unescape(text):
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "r": "\r", "t": "\t"}.get(m[1], m[1]), text)


def rows(path):
    return [[unescape(cell) for cell in line.split("\t")] for line in path.read_text().splitlines()]


def literal(text):
    return json.dumps(text, ensure_ascii=True).replace("$", "\\$")


def generate(oracle):
    cases = []
    for module, kind, special in [("NASB", "osis", "Mark.10.34"),
                                  ("ISV", "thml", "1Cor.14.33"),
                                  ("FinPR", "gbf", None),
                                  ("StrongsGreek", "plaintext", None)]:
        source_path = oracle / f"{module}.inputs.tsv"
        expected_path = oracle / f"{module}.osis.tsv"
        inputs = {row[0]: row[3] for row in rows(source_path) if row[1] == "source"}
        expected = rows(expected_path)
        # Verse rows have only the BookData verse/div envelope. Dictionary rows have
        # the generated title envelope. Strip those exact bytes, not XML whitespace.
        eligible = [row for row in expected if ("<verse " in row[3] if kind != "plaintext" else True)]
        chosen = ([next(row for row in eligible if row[0] == special)] if special else [])
        chosen += [row for row in eligible if row[0] != special][:10 - len(chosen)]
        assert len(chosen) == 10
        cases.append(f"    // {module}: inputs SHA-256 {hashlib.sha256(source_path.read_bytes()).hexdigest()}")
        cases.append(f"    // {module}: output SHA-256 {hashlib.sha256(expected_path.read_bytes()).hexdigest()}")
        for key, stage, digest, xml in chosen:
            assert hashlib.sha256(xml.encode()).hexdigest() == digest
            if kind == "plaintext":
                prefix = f'<div><title type="x-gen">{key}</title>'
                assert xml.startswith(prefix) and xml.endswith('</div>')
                fragment = xml[len(prefix):-len('</div>')]
            else:
                match = re.fullmatch(r'<div><verse osisID="[^"]+" verseOrdinal="[0-9]+">(.*)</verse></div>', xml, re.S)
                assert match, (module, key)
                fragment = match[1]
            cases.append(f"    FrozenFilterCase({literal(module)}, {literal(kind)}, {literal(key)}, {stage}, {literal(inputs[key])}, {literal(fragment)}),")
    return '''package org.crosswire.jsword.book.filter

// Generated by scripts/k5-gen-filter-test.py from immutable .local/k5-oracle/jsword.
// Only BookData's exact outer envelope is removed; expected raw fragment bytes are unchanged.
internal data class FrozenFilterCase(val module: String, val type: String, val key: String,
    val acceptedStage: Int, val input: String, val expected: String)

internal val frozenFilterCases = listOf(
''' + '\n'.join(cases) + '\n)\n'


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("oracle", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.oracle))
