package org.crosswire.jsword.passage

/**
 * An implementation of some of the easier methods from Key.
 *
 * @see gnu.lgpl.License The GNU Lesser General Public License for details.
 * @author Joe Walker
 */
abstract class AbstractKeyList : Key {
    /** Copies the fields and preserves the deep-copy steps of the original clone. */
    protected constructor(copyFrom: AbstractKeyList) {
        name = copyFrom.name
    }

    /**
     * Build an AbstractKeyList with the given name.
     *
     * @param name
     */
    protected constructor(name: String?) {
        this.name = name
    }

    /* (non-Javadoc)
     * @see org.crosswire.jsword.passage.Key#isEmpty()
     */
    override fun isEmpty(): Boolean {
        return getCardinality() == 0
    }

    /* (non-Javadoc)
     * @see org.crosswire.jsword.passage.Key#contains(org.crosswire.jsword.passage.Key)
     */
    override fun contains(key: Key?): Boolean {
        return indexOf(key) >= 0
    }

    /* (non-Javadoc)
     * @see org.crosswire.jsword.passage.Key#retainAll(org.crosswire.jsword.passage.Key)
     */
    override fun retainAll(key: Key?) {
        val shared: Key = DefaultKeyList()
        shared.addAll(key)
        retain(this, shared)
    }

    override fun toString(): String {
        return getName()
    }

    /**
     * Override the default name with a custom name. If the name is null then a
     * name will be generated by concatenating the names of all the elements of
     * this node.
     * @param name
     */
    open fun setName(name: String?) {
        this.name = name
    }

    /* (non-Javadoc)
     * @see org.crosswire.jsword.passage.Key#getName()
     */
    override fun getName(): String {
        if (name != null) {
            return name!!
        }

        val visitor: DefaultKeyVisitor = NameVisitor()
        KeyUtil.visit(this, visitor)
        return visitor.toString()
    }

    /* (non-Javadoc)
     * @see org.crosswire.jsword.passage.Key#getName(org.crosswire.jsword.passage.Key)
     */
    override fun getName(base: Key?): String {
        return getName()
    }

    /* (non-Javadoc)
     * @see org.crosswire.jsword.passage.Key#getRootName()
     */
    override fun getRootName(): String {
        return getName()
    }

    /* (non-Javadoc)
     * @see org.crosswire.jsword.passage.Key#getOsisRef()
     */
    override fun getOsisRef(): String {
        val visitor: DefaultKeyVisitor = OsisRefVisitor()
        KeyUtil.visit(this, visitor)
        return visitor.toString()
    }

    /* (non-Javadoc)
     * @see org.crosswire.jsword.passage.Key#getOsisID()
     */
    override fun getOsisID(): String {
        val visitor: DefaultKeyVisitor = OsisIDVisitor()
        KeyUtil.visit(this, visitor)
        return visitor.toString()
    }

    override fun equals(other: Any?): Boolean {
        // Since this can not be null
        if (other == null) {
            return false
        }

        // Check that that is the same as this
        // Don't use instanceOf since that breaks inheritance
        if (other.javaClass != this.javaClass) {
            return false
        }

        return compareTo(other as Key) == 0
    }

    override fun hashCode(): Int {
        return getName().hashCode()
    }

    /* (non-Javadoc)
     * @see java.lang.Comparable#compareTo(java.lang.Object)
     */
    override fun compareTo(other: Key?): Int {
        if (this === other) {
            return 0
        }

        if (other == null) {
            // he is empty, we are not so he is greater
            return -1
        }

        val ret = this.getName().compareTo(other.getName())

        if (ret != 0) {
            return ret
        }

        // Compare the contents.
        val thisIter = this.iterator()
        val thatIter = other.iterator()

        var thisfirst: Key? = null
        var thatfirst: Key? = null

        if (thisIter.hasNext()) {
            thisfirst = thisIter.next()
        }

        if (thatIter.hasNext()) {
            thatfirst = thatIter.next()
        }

        if (thisfirst == null) {
            if (thatfirst == null) {
                // we are both empty, and rank the same
                return 0
            }
            // i am empty, he is not so we are greater
            return 1
        }

        if (thatfirst == null) {
            // he is empty, we are not so he is greater
            return -1
        }

        return thisfirst.getName().compareTo(thatfirst.getName())
    }

    abstract override fun clone(): AbstractKeyList

    /**
     * The `NameVisitor` constructs a readable representation of the
     * Passage.
     */
    internal open class NameVisitor : DefaultKeyVisitor() {
        override fun visitLeaf(key: Key?) {
            buffer.append(key!!.getName())
            buffer.append(AbstractPassage.REF_PREF_DELIM)
        }

        override fun toString(): String {
            var reply = buffer.toString()
            if (reply.length > 0) {
                // strip off the final ", "
                reply = reply.substring(0, reply.length - AbstractPassage.REF_PREF_DELIM.length)
            }

            return reply
        }

        @JvmField
        protected var buffer: StringBuilder = StringBuilder()
    }

    /**
     * The `OsisRefVisitor` constructs a readable representation of
     * the Passage, using OSIS names.
     */
    internal open class OsisRefVisitor : NameVisitor() {
        override fun visitLeaf(key: Key?) {
            buffer.append(key!!.getOsisRef())
            buffer.append(AbstractPassage.REF_PREF_DELIM)
        }
    }

    /**
     * The `OsisRefVisitor` constructs a readable representation of
     * the Passage, using OSIS names.
     */
    internal open class OsisIDVisitor : NameVisitor() {
        override fun visitLeaf(key: Key?) {
            buffer.append(key!!.getOsisID())
            buffer.append(AbstractPassage.REF_OSIS_DELIM)
        }

        override fun toString(): String {
            var reply = super.toString()
            if (reply.length > 0) {
                // strip off the final " "
                reply = reply.substring(0, reply.length - AbstractPassage.REF_OSIS_DELIM.length)
            }

            return reply
        }
    }

    /**
     * The common user visible name for this work
     */
    private var name: String? = null

    companion object {
        /**
         * Utility to remove all the keys from alter that are not in base
         *
         * @param alter
         *            The key to remove keys from
         * @param base
         *            The check key
         */
        @JvmStatic
        protected fun retain(alter: Key?, base: Key?) {
            val iter = alter!!.iterator()
            while (iter.hasNext()) {
                val sublist = iter.next()
                if (sublist.canHaveChildren()) {
                    retain(sublist, base)
                    if (sublist.isEmpty()) {
                        iter.remove()
                    }
                } else {
                    if (!base!!.contains(sublist)) {
                        iter.remove()
                    }
                }
            }
        }
    }
}
