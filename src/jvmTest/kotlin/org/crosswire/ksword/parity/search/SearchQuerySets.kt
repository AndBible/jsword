package org.crosswire.ksword.parity.search

import org.crosswire.jsword.index.search.SearchType

/**
 * One query of the corpus parity matrix. [expectHit] marks queries built from the module's own text that should find
 * verses (the non-empty-results floor of [SearchCorpusParityTest] counts only those).
 */
data class SearchQuerySpec(val query: String, val expectHit: Boolean)

/** Words picked from one module's text (see [SearchQueryWordPicker]): mid-frequency words, adjacent pairs and triples. */
data class ModuleWords(val words: List<String>, val pairs: List<String>, val triples: List<String>)

/**
 * The K6 search-parity query matrix (spec 6.2): for every corpus module a fixed list of queries built from words of
 * that module's own text ([MODULE_WORDS], a seeded pick, regenerated by [SearchQueryWordPicker]).
 *
 * The all/any/phrase/start/spell forms go through [SearchType.decorate], i.e. the strings the UI sends
 * (`SearchControl.decorateSearchString`: `+a +b`, `a b`, `"a b"`, `a*`, `a~`), with the Bible-section term of the
 * app (`+[Gen-Mal]`, `+[Mat-Rev]`, `+[Book]`) in front, as well as the JSword blur form `a ~2 b` and `-[..]`.
 * `strong:` queries exist for the modules with Strong's numbers. The K6-3 forms (`heading:x`, `^` boosts,
 * `{a TO b}`) are in the matrix on purpose: they are expected to differ (K6 throws `UnsupportedSearchSyntaxException`)
 * and are approved by rule in `parity/approved-differences.md`.
 */
val QUERY_SPECS: Map<String, List<SearchQuerySpec>> by lazy { MODULE_WORDS.mapValues { (initials, w) -> buildSpecs(initials, w) } }

/** The query strings of [QUERY_SPECS] per module (at least 25 each). */
val QUERY_SETS: Map<String, List<String>> by lazy { QUERY_SPECS.mapValues { (_, specs) -> specs.map { it.query } } }

/** Queries per module that should find verses (non-empty on both sides), input of the floor assertion. */
val EXPECTED_HITS: Map<String, Set<String>> by lazy {
    QUERY_SPECS.mapValues { (_, specs) -> specs.filter { it.expectHit }.map { it.query }.toSet() }
}

