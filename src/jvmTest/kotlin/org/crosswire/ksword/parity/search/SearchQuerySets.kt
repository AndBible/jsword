private fun parts(s: String): List<String> =
    if (s.contains(' ')) s.split(' ').filter { it.isNotEmpty() } else if (s.length == 4) listOf(s.substring(0, 2), s.substring(2)) else listOf(s)

private fun buildSpecs(initials: String, mw: ModuleWords): List<SearchQuerySpec> {
    val specs = LinkedHashMap<String, Boolean>() // keeps the first flag of a duplicate query
    fun hit(q: String) { specs.putIfAbsent(q, true) }
    fun any(q: String) { specs.putIfAbsent(q, false) }

    val w = mw.words
    val (a, b, c, d) = w
    val p1 = mw.pairs[0]; val p2 = mw.pairs[1]; val p3 = mw.pairs[2]
    val t1 = mw.triples[0]; val t2 = mw.triples[1]
    val (x1, x2) = parts(p1).let { it[0] to it.last() }
    val (y1, y2) = parts(p2).let { it[0] to it.last() }
    val tparts = parts(t1)
    val cjk = initials in setOf("ChiUns", "ChiUn", "JapKougo")
    val section = listOf("+[Gen-Mal] ", "+[Mat-Rev] ", "+[Rom] ")

    // single word, case
    hit(a); hit(b); hit(w[4]); hit(a.uppercase()); hit(a.replaceFirstChar { it.uppercase() })
    // all / any / phrase as the UI sends them (SearchType.decorate)
    hit(SearchType.ALL_WORDS.decorate("$x1 $x2"))
    hit(SearchType.ALL_WORDS.decorate("$y1 $y2"))
    hit(SearchType.ALL_WORDS.decorate(tparts.joinToString(" ")))
    hit(SearchType.ANY_WORDS.decorate("$a $b $c"))
    hit(SearchType.ANY_WORDS.decorate("$x1 $x2"))
    hit(SearchType.PHRASE.decorate(p1)); hit(SearchType.PHRASE.decorate(p2)); hit(SearchType.PHRASE.decorate(p3))
    hit(SearchType.PHRASE.decorate(t1)); hit(SearchType.PHRASE.decorate(t2))
    any(SearchType.PHRASE.decorate("$x2 $x1"))
    any(SearchType.PHRASE.decorate("$a $b"))
    hit(SearchType.START_WORDS.decorate(a.take(maxOf(1, a.length / 2))))
    hit(SearchType.SPELL_WORDS.decorate(a))
    any(SearchType.NOT_WORDS.decorate(a))
    // section term of the app (+[Gen-Mal] / +[Mat-Rev] / +[Book]) and JSword range/blur forms
    any(section[0] + SearchType.ALL_WORDS.decorate("$x1 $x2"))
    any(section[1] + SearchType.ANY_WORDS.decorate("$a $b"))
    any(section[2] + SearchType.PHRASE.decorate(p1))
    any(section[0] + a); any(section[1] + a); any(section[2] + a)
    hit("+[Gen-Rev] $a"); hit("-[Gen-Mal] $a"); any("-[Mat-Rev] $x1")
    any("+[Gen-Mal] +[Mat-Rev] $a")
    any("+[Gen-Mal]")
    hit("$x1 ~2 $x2"); hit("$x1 ~ $x2"); any("$a ~3 $b"); any("+[Gen-Mal] $x1 ~5 $x2")
    // booleans, prohibited, the five Review shapes, nesting
    hit("$x1 AND $x2"); hit("$x1 OR $x2"); hit("$x1 && $x2"); hit("$x1 || $x2")
    hit("$x1 NOT $x2"); hit("$x1 AND NOT $x2"); hit("!$a"); hit("NOT $a"); hit("-$a $b"); hit("+$x1 -$x2"); hit("$x1 -$x2")
    hit("$x1 AND $x2 OR $a"); hit("-$x1 $x2"); hit("$x1 -$x2 AND $y1"); hit("NOT $a AND $x1"); hit("$x1 AND ($x2 OR $a) NOT $b")
    hit("($x1 OR $a) AND ($x2 OR $b)"); hit("(($x1)) AND ($x2)"); hit("+($x1 $a) +$x2"); any("-$a"); any("-$a -$b")
    hit("content:$a"); hit("content:($x1 $x2)")
    // wildcards: trailing, inner, leading, ?, prefix of a stemmed word
    val k = maxOf(1, minOf(a.length / 2, 4))
    hit("${a.take(k)}*"); hit("${b.take(k)}*"); hit("${x1.take(k)}*")
    hit("${a.take(1)}*${a.takeLast(1)}"); hit("${b.take(1)}*${b.takeLast(1)}")
    hit("*${a.takeLast(k)}"); hit("*${b.takeLast(k)}")
    if (a.length >= 2) { hit(a.replaceRange(a.length / 2, a.length / 2 + 1, "?")); hit("${a.dropLast(1)}?"); hit("?${a.drop(1)}") }
    hit(b.replaceRange(b.length / 2, b.length / 2 + 1, "?"))
    any("${a.take(k)}*${b.takeLast(1)}"); any("*"); any("?"); any("**"); any("*?*"); any("${a}*${a}")
    // fuzzy at 0.5, 0.7, 0.9
    hit("$a~"); hit("$a~0.5"); hit("$b~0.7"); hit("$c~0.9"); hit("$x1~0.6"); any("$d~0.1")
    // proximity, both orders
    hit("\"$x1 $x2\"~3"); any("\"$x2 $x1\"~3"); hit("\"$x1 $x2\"~10"); any("\"$x2 $x1\"~10"); hit("\"$y1 $y2\"~2")
    if (tparts.size >= 3) { hit("\"${tparts.joinToString(" ")}\"~4"); any("\"${tparts.reversed().joinToString(" ")}\"~6") }
    hit("\"$x1 $x2\"~0")
    // empty, no hit, operators only, stray quotes, odd input the UI sends verbatim
    for (q in listOf("", " ", "+ -", "+", "-", "!", "AND", "OR", "NOT", "()", "\"", "\"\"", "\"$a", "$a\"", "$a AND", "AND $a", "$a OR", "(\$a", "$a)", "\\*", "~", "&&", "||")) any(q)
    any("zzzzqxv"); any("$a zzzzqxv"); any("+$a +zzzzqxv"); any("zzzzqxv*"); any("zzzzqxv~"); any("\"$a zzzzqxv\"")
    // K6-3 forms: expected to differ, approved by rule
    any("heading:$a"); any("note:$a"); any("$a^2"); any("($x1 $x2)^2"); any("\"$x1 $x2\"^3"); any("{$a TO $b}"); any("$a:$b")
    // Review Focus 1: region/script codes (zh-Hans, zh-Hant) select the analyzer by the base language
    if (initials == "ChiUns" || initials == "ChiUn") {
        val faith = "faith"
        hit("$a $faith"); any("+$a +$faith"); any("\"$a $faith\""); any("$a$faith"); any("$faith$a"); hit("$a OR Jesus"); any("$x1 AND $faith"); any("神爱 AND $faith")
        any("神"); any("神爱世人"); any("\"神爱世人\""); any("上帝"); any("+神 +爱"); any("神 爱"); any("，"); any("。")
        any("神$faith~"); any("${a.take(1)}*$faith")
    }
    // K6-9: Strong's numbers
    STRONGS[initials]?.let { s ->
        val exp = initials == "KJV" || initials == "Byz"
        fun st(q: String) { if (exp) hit(q) else any(q) }
        st("strong:${s[0]}"); st("strong:${s[1]}"); st("strong:${s[2]}"); st("strong:${s[3]}")
        st("strong:${s[0]} AND $a"); st("strong:${s[1]} -$a"); st("$a strong:${s[1]}"); st("+strong:${s[0]} +$x1")
        st("strong:${s[1]} strong:${s[2]}"); st("strong:${s[1]} AND strong:${s[3]}"); st("strong:${s[1]} -strong:${s[3]}")
        any("strong:${s[4]}"); any("+[Mat-Rev] strong:${s[1]}"); any("+[Gen-Mal] strong:${s[0]}"); any("strong:${s[0].uppercase()}")
        any("strong:${s[0].take(2)}*"); any("strong:${s[0].take(3)}?"); any("strong:*"); any("strong:?"); any("strong:xyz"); any("strong:")
        any("strong:\"${s[0]} ${s[1]}\""); any("strong:${s[0]}~"); any("strong:(${s[0]} ${s[1]})")
    }
    GAP_PHRASES[initials]?.forEach { p ->
        any("\"$p\""); any("\"$p\"~2"); any(SearchType.ALL_WORDS.decorate(p)); any(p)
    }
    EMPTY_TERM[initials]?.forEach { any(it) }
    if (cjk) { any("${a.take(1)}*"); any("*${a.takeLast(1)}"); any("${a.take(1)}?"); any("?${a.takeLast(1)}") }
    if (initials == "WLC") any("\"${a} ${b}\"~5") // Review Focus 2: hbo has no analyzer of its own, so the simple one
    return specs.map { SearchQuerySpec(it.key, it.value) }
}

